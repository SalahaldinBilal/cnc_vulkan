const IMAGE_BASE: usize = 0x0040_0000;

static DETECTED: OnceLock<Option<&'static Build>> = OnceLock::new();

pub fn build() -> Option<&'static Build> {
    *DETECTED.get_or_init(|| {
        let base = unsafe { GetModuleHandleW(std::ptr::null()) } as usize;
        if base != IMAGE_BASE {
            log!("game image loaded at {base:#x} instead of {IMAGE_BASE:#x}, game patches disabled");
            return None;
        }
        let image_end = base + image_size(base);
        for k in KNOWN {
            let mismatch = k
                .checks
                .iter()
                .find(|(addr, bytes)| addr + bytes.len() > image_end || !matches(*addr, bytes));
            match mismatch {
                None => {
                    log!("recognized {}", k.build.name);
                    return Some(&k.build);
                }
                Some((addr, _)) => log!("not {}: bytes at {addr:#010x} differ", k.build.name),
            }
        }
        log!("unrecognized game.dat build, game patches disabled");
        None
    })
}

/// For modules not ported to Generals yet.
pub fn zero_hour() -> bool {
    build().is_some_and(|b| b.game == Game::ZeroHour)
}

/// A module's addresses for the running build: Zero Hour's, or Generals' once the module is ported.
pub fn pick<T>(zero_hour: &'static T, generals: Option<&'static T>) -> Option<&'static T> {
    match build()?.game {
        Game::ZeroHour => Some(zero_hour),
        Game::Generals => generals,
    }
}

/// Start and end of the game's image in memory.
pub fn image_range() -> (usize, usize) {
    (IMAGE_BASE, IMAGE_BASE + image_size(IMAGE_BASE))
}

/// Start and end of the game's code section.
pub fn code_range() -> (usize, usize) {
    const IMAGE_SCN_CNT_CODE: u32 = 0x20;
    unsafe {
        let nt = IMAGE_BASE + *((IMAGE_BASE + 0x3C) as *const u32) as usize;
        let count = *((nt + 6) as *const u16) as usize;
        let first = nt + 0x18 + *((nt + 0x14) as *const u16) as usize;
        for i in 0..count {
            let s = first + i * 40;
            if *((s + 36) as *const u32) & IMAGE_SCN_CNT_CODE != 0 {
                let start = IMAGE_BASE + *((s + 12) as *const u32) as usize;
                return (start, start + *((s + 8) as *const u32) as usize);
            }
        }
    }
    (IMAGE_BASE, IMAGE_BASE)
}

/// The call instruction ending at `at`, if there is one: `Some(Some(target))` for a direct call,
/// `Some(None)` for an indirect one.
pub fn call_before(at: usize) -> Option<Option<usize>> {
    let b = |back: usize| unsafe { *((at - back) as *const u8) };
    if b(5) == 0xE8 {
        let rel = i32::from_le_bytes([b(4), b(3), b(2), b(1)]);
        return Some(Some((at as isize + rel as isize) as usize));
    }
    let call = |len: usize, modes: &[(u8, bool)]| {
        let m = b(len - 1);
        b(len) == 0xFF && (m >> 3) & 7 == 2 && modes.iter().any(|&(mode, sib)| m >> 6 == mode && (m & 7 == 4) == sib)
    };
    // `call [abs32]` is how the game calls Windows, which never leads back into the game.
    if b(6) == 0xFF && b(5) == 0x15 {
        return None;
    }
    let indirect = (b(2) == 0xFF && b(1) >> 6 == 3 && (b(1) >> 3) & 7 == 2)
        || (call(2, &[(0, false)]) && b(1) & 7 != 5)
        || call(3, &[(1, false), (0, true)])
        || call(4, &[(1, true)])
        || (call(6, &[(2, false), (0, false)]) && (b(5) >> 6 == 2 || b(5) & 7 == 5))
        || call(7, &[(2, true)]);
    indirect.then_some(None)
}

/// Return addresses into the game's code on this thread's stack, nearest first, as many as fit
/// in `out`. Stale values left in the stack can look like one, so a direct call only counts when
/// it goes to a function that could hold the previous return address (at most 16 KB before it).
/// For diagnostics.
pub fn stack_callers(out: &mut [usize]) -> usize {
    #[cfg(target_arch = "x86")]
    {
        if build().is_none() {
            return 0;
        }
        let top: usize;
        unsafe { std::arch::asm!("mov {}, fs:[4]", out(reg) top, options(nostack, readonly, preserves_flags)) };
        unsafe { stack_callers_between(&top as *const usize as usize, top, out) }
    }
    #[cfg(not(target_arch = "x86"))]
    {
        let _ = out;
        0
    }
}

/// Same, for any thread's stack from `at` up to `top`, which must stay readable.
pub unsafe fn stack_callers_between(mut at: usize, top: usize, out: &mut [usize]) -> usize {
    if build().is_none() {
        return 0;
    }
    let (start, end) = code_range();
    let mut n = 0;
    while n < out.len() && at + 4 <= top {
        let v = unsafe { *(at as *const usize) };
        let previous = n.checked_sub(1).map(|i| out[i]);
        if v >= start + 8 && v < end && previous != Some(v) {
            let windows_call = n == 0 && unsafe { *((v - 6) as *const u8) == 0xFF && *((v - 5) as *const u8) == 0x15 };
            let fits = windows_call
                || match (call_before(v), previous) {
                    (None, _) => false,
                    (Some(Some(target)), Some(p)) => target <= p && p - target < 0x4000,
                    _ => true,
                };
            if fits {
                out[n] = v;
                n += 1;
            }
        }
        at += 4;
    }
    n
}

/// SizeOfImage from the PE optional header.
pub fn image_size(base: usize) -> usize {
    unsafe {
        let nt = base + *((base + 0x3C) as *const u32) as usize;
        *((nt + 0x50) as *const u32) as usize
    }
}

fn matches(addr: usize, expected: &[u8]) -> bool {
    let actual = unsafe { std::slice::from_raw_parts(addr as *const u8, expected.len()) };
    actual == expected
}

/// Pointer to the game's GlobalData, or `None` before the game has created it.
fn global_data(build: &Build) -> Option<*mut u8> {
    let p = unsafe { *(build.global_data as *const usize) };
    (p != 0).then_some(p as *mut u8)
}

/// Makes the game believe it runs windowed, so its alt-tab and device handling match what the
/// device actually is.
pub fn set_windowed() {
    let Some(build) = build() else { return };
    match global_data(build) {
        Some(gd) => {
            let flag = unsafe { gd.add(global_data::WINDOWED) };
            let before = unsafe { *flag };
            unsafe { *flag = 1 };
            log!("GlobalData windowed flag set (was {before})");
        }
        None => log!("GlobalData not created yet, windowed flag not set"),
    }
}

/// Goes straight to the main menu instead of playing the intro movies. Runs before the first
/// client update.
pub fn skip_intro() {
    let Some(build) = build() else { return };
    let Some(gd) = global_data(build) else {
        log!("GlobalData not created yet, intro movies not skipped");
        return;
    };
    unsafe {
        let play = gd.add(global_data::PLAY_INTRO);
        if *play != 0 {
            *play = 0;
            *gd.add(build.after_intro) = 1;
            log!("intro movies skipped");
        }
    }
}

/// Overrides the resolution the game read from Options.ini or the command line. Runs before the
/// game reads it to create its device.
pub fn set_resolution(width: u32, height: u32) {
    let Some(build) = build() else { return };
    let Some(gd) = global_data(build) else {
        log!("GlobalData not created yet, resolution not set");
        return;
    };
    unsafe {
        let x = gd.add(global_data::X_RESOLUTION) as *mut u32;
        let y = gd.add(global_data::Y_RESOLUTION) as *mut u32;
        log!("resolution set to {width}x{height} (game had {}x{})", *x, *y);
        *x = width;
        *y = height;
    }
}

/// Lets the options menu list every aspect ratio instead of only 4:3.
pub fn unlock_aspect_ratios() {
    let Some(build) = build() else { return };
    match build.mode_filter {
        ModeFilter::Bounds { min, max } => unsafe {
            write_f32(min, 0.0);
            write_f32(max, 100.0);
        },
        ModeFilter::Tolerance { fcomps } => {
            static ANY_ASPECT: f64 = 100.0;
            for at in fcomps {
                unsafe { write_u32(at + 2, &ANY_ASPECT as *const f64 as u32) };
            }
        }
    }
    log!("options menu now lists all aspect ratios");
}

/// Overwrites the instruction at `at` with a jump to `target`.
pub unsafe fn patch_jump(at: usize, target: usize) {
    unsafe { write_code(at, &branch(0xE9, at, target)) };
}

/// Overwrites `len` bytes at `at` with a call to `target` followed by a jump past the rest.
pub unsafe fn replace_with_call(at: usize, len: usize, target: usize) {
    let mut code = vec![0x90u8; len];
    code[..5].copy_from_slice(&branch(0xE8, at, target));
    if len >= 7 {
        code[5] = 0xEB;
        code[6] = (len - 7) as u8;
    }
    unsafe { write_code(at, &code) };
}

/// Where the `call rel32` at `at` goes, if there is one.
pub fn call_target(at: usize) -> Option<usize> {
    let bytes = unsafe { std::slice::from_raw_parts(at as *const u8, 5) };
    (bytes[0] == 0xE8).then(|| {
        let rel = i32::from_le_bytes([bytes[1], bytes[2], bytes[3], bytes[4]]);
        (at as isize + 5 + rel as isize) as usize
    })
}

pub unsafe fn write_u32(at: usize, value: u32) {
    unsafe { write_code(at, &value.to_le_bytes()) };
}

fn branch(opcode: u8, at: usize, target: usize) -> [u8; 5] {
    let rel = (target as isize - (at as isize + 5)) as i32;
    let mut code = [opcode, 0, 0, 0, 0];
    code[1..].copy_from_slice(&rel.to_le_bytes());
    code
}

pub unsafe fn write_code(at: usize, code: &[u8]) {
    unsafe {
        let mut old = 0;
        VirtualProtect(at as *const c_void, code.len(), PAGE_EXECUTE_READWRITE, &mut old);
        std::ptr::copy_nonoverlapping(code.as_ptr(), at as *mut u8, code.len());
        VirtualProtect(at as *const c_void, code.len(), old, &mut old);
        FlushInstructionCache(GetCurrentProcess(), at as *const c_void, code.len());
    }
}

/// Points the `call rel32` at `at` to `target`.
pub unsafe fn patch_call(at: usize, target: usize) {
    let rel = (target as isize - (at as isize + 5)) as i32;
    unsafe {
        let mut old = 0;
        VirtualProtect((at + 1) as *const c_void, 4, PAGE_EXECUTE_READWRITE, &mut old);
        std::ptr::copy_nonoverlapping(rel.to_le_bytes().as_ptr(), (at + 1) as *mut u8, 4);
        VirtualProtect((at + 1) as *const c_void, 4, old, &mut old);
        FlushInstructionCache(GetCurrentProcess(), at as *const c_void, 5);
    }
}

unsafe fn write_f32(addr: usize, value: f32) {
    unsafe {
        let mut old = 0;
        VirtualProtect(addr as *const c_void, 4, PAGE_READWRITE, &mut old);
        *(addr as *mut f32) = value;
        VirtualProtect(addr as *const c_void, 4, old, &mut old);
    }
}
