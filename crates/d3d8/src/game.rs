#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Game {
    ZeroHour,
    Generals,
}

pub struct Build {
    pub game: Game,
    pub name: &'static str,
    /// Address of the `TheGlobalData` pointer.
    pub global_data: usize,
    /// GlobalData `m_useFpsLimit`, the engine frame cap switch.
    pub use_fps_limit: usize,
    /// GlobalData flag set once the intro is done. The next client update then opens the main menu.
    pub after_intro: usize,
    pub mode_filter: ModeFilter,
    /// TextureClass: its Direct3D texture.
    pub texture_d3d: usize,
    /// Address of the `TheDisplay` pointer. Its vtable has getWidth at +0x20 and getHeight at +0x24.
    pub the_display: usize,
    /// Top-of-stack pointer of the parent stack used while parsing .wnd files. Storage follows it.
    pub window_parent_stack: usize,
    /// Start of the SCREENRECT scaling block in the .wnd parser. `ui::screen_rect_stub` resumes
    /// right after it, at 0x006DCB9D.
    pub screen_rect_patch: usize,
}

/// How the options menu's display mode list keeps only 4:3 modes.
pub enum ModeFilter {
    /// The aspect ratio must lie strictly between these two floats.
    Bounds { min: usize, max: usize },
    /// `fcomp qword [tolerance]` instructions comparing |w/h - 4/3| to a double the whole game shares.
    Tolerance { fcomps: [usize; 2] },
}

pub mod global_data {
    pub const WINDOWED: usize = 0x20;
    pub const X_RESOLUTION: usize = 0x24;
    pub const Y_RESOLUTION: usize = 0x28;
    pub const FRAMES_PER_SECOND_LIMIT: usize = 0x18;
    /// INI `PlayIntro`: the client update plays the EA logo movie while it's set.
    pub const PLAY_INTRO: usize = 0x819;
    /// The sky box scale. The water's Render draws the sky box when it isn't 0.
    pub const SKY_BOX_SCALE: usize = 0x164;
}

