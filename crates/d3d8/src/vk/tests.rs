#[test]
fn sixteen_bit_texels_expand_to_bgra() {
    let info = super::format::info(super::format::R5G6B5).unwrap();
    let src: Vec<u8> = [0xF800u16, 0x07E0, 0x001F, 0xFFFF].iter().flat_map(|p| p.to_le_bytes()).collect();
    let mut dst = vec![0u8; 16];
    info.to_gpu(&src, src.len(), 4, 1, &mut dst);
    assert_eq!(dst, [0, 0, 255, 255, 0, 255, 0, 255, 255, 0, 0, 255, 255, 255, 255, 255]);
}

#[test]
fn fixed_function_shaders_compile() {
    let vs = ff::vertex();
    shader::compile(&vs, Stage::Vertex).unwrap_or_else(|e| panic!("{e}"));
    let fs = ff::fragment();
    shader::compile(&fs, Stage::Fragment).unwrap_or_else(|e| panic!("{e}"));
}

#[test]
fn game_pixel_shaders_translate_and_compile() {
    for (i, hex) in PIXEL_SHADERS.iter().enumerate() {
        let (source, _) = sm1::translate_pixel(&tokens(hex)).unwrap_or_else(|e| panic!("pixel shader {i}: {e}"));
        shader::compile(&source, Stage::Fragment).unwrap_or_else(|e| panic!("pixel shader {i}: {e}\n{source}"));
    }
}

#[test]
fn game_vertex_shader_translates_and_compiles() {
    let (decl, _) = sm1::parse_declaration(&tokens(TREE_DECL)).unwrap();
    assert_eq!(decl.elements.len(), 4);
    assert_eq!(decl.elements[3].reg, 7);
    assert_eq!(decl.elements[3].offset, 28);
    let source = sm1::translate_vertex(&tokens(TREE_VS), &decl).unwrap();
    shader::compile(&source, Stage::Vertex).unwrap_or_else(|e| panic!("{e}\n{source}"));
}
